/** Until a role has its own steps: one step per suggested course module. */
function fromModules(phase: Phase): Step[] {
  return phase.modules.map((id) => {
    const m = modules.find((x) => x.id === id)!;
    return {
      id: `${phase.id}-${m.id}`,
      title: m.title,
      video: m.id,
      task: m.tasks[0],
      reflect: "Энэ хичээлээс юу сурав? Маргааш юуг өөрөөр хийх вэ?",
    };
  });
}

export function pathFor(role: FounderType["id"], phase: Phase): Step[] {
  return role === "hustler" ? ceo[phase.id] : fromModules(phase);
}

/** What one step can pay this founder in full. */
export function stepSparks(s: Step, role: FounderType) {
  return VIDEO_SPARKS + rewardFor(s.task, role) + NOTE_SPARKS;
}

export type StepLog = { video?: boolean; task?: boolean; note?: string };

export function earned(s: Step, role: FounderType, log: StepLog | undefined) {
  if (!log) return 0;
  return (log.video ? VIDEO_SPARKS : 0) + (log.task ? rewardFor(s.task, role) : 0) + (log.note ? NOTE_SPARKS : 0);
}

export const isDone = (log: StepLog | undefined) => Boolean(log?.video && log.task && log.note);

/** Sparks a stage pays in full, and how many of them unlock the next stage. */
export function stageGoal(role: FounderType, phase: Phase) {
  const total = pathFor(role.id, phase).reduce((sum, s) => sum + stepSparks(s, role), 0);
  return { total, unlock: Math.round(total * UNLOCK_SHARE) };
}

export function stageEarned(role: FounderType, phase: Phase, logs: Record<string, StepLog>) {
  return pathFor(role.id, phase).reduce((sum, s) => sum + earned(s, role, logs[s.id]), 0);
}

export function totalEarned(role: FounderType, logs: Record<string, StepLog>) {
  return phases.reduce((sum, p) => sum + stageEarned(role, p, logs), 0);
}

