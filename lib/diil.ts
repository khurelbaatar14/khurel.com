// DIIL for startups (/founders): the path a founder walks after picking a role and a stage. Each step
// is a video, then a real-world task, then a short reflection, and each of the three earns sparks
// ("оноо"). Sparks fill the bar that unlocks the next stage, and can be spent on a meeting with one of
// the DIIL co-founders. Copy is everyday Mongolian, written to "чи".
//
// The CEO (Hustler) and CTO (Hacker) paths are written step by step. The CMO path, and any stage a
// path doesn't cover yet, is still built from the course modules (lib/founder-course.ts).

import { phases, rewardFor, type FounderType, type Phase, type Quest } from "@/lib/founder";
import { modules } from "@/lib/founder-course";

export type Step = {
  id: string;
  title: string;
  /** Course module whose video this step plays. */
  video: string;
  task: Quest;
  /** The reflection question. */
  reflect: string;
  /** More for the task: a table, a prompt to copy, rules, a tip or warning, or a checklist to tick off. */
  extras?: Extra[];
};

export type Extra =
  | { kind: "table"; head: string[]; rows: string[][] }
  | { kind: "prompt"; text: string }
  | { kind: "rules"; title: string; items: string[] }
  | { kind: "tip"; text: string }
  | { kind: "warning"; text: string }
  /** The task can only be marked done once every item is ticked. */
  | { kind: "checklist"; items: string[] };

export const VIDEO_SPARKS = 10;
export const NOTE_SPARKS = 20;
/** Share of a stage's sparks that unlocks the next stage. */
export const UNLOCK_SHARE = 0.6;
export const MEETING_COST = 500;

