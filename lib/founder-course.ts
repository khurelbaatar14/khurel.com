import { taskById, type FounderType, type Quest } from "@/lib/founder";

// The Founder Path course: 16 short modules, each a video (recorded later; `points` are its
// outline), a tip for each founder role, and real-world tasks that earn sparks. Most tasks come
// from the task library in lib/founder.ts; the rest are defined here.

export type Module = {
  id: string;
  title: string;
  /** One line: what the founder walks away with. */
  promise: string;
  /** Planned video length. */
  minutes: number;
  /** Bunny Stream video ID once recorded. */
  video?: string;
  /** Key ideas; also the video's outline. */
  points: string[];
  /** Where time-sensitive facts come from, and when they were checked. */
  note?: string;
  tips: Record<FounderType["id"], string>;
  tasks: Quest[];
};

const task = (id: string) => {
  const q = taskById[id];
  if (!q) throw new Error(`Unknown task: ${id}`);
  return q;
};

